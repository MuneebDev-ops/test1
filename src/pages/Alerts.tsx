import { useMemo, useState } from 'react'
import { Link } from 'react-router-dom'
import { Icon } from '../components/Icon'
import { Banner, PageHeader, Pill } from '../components/chrome'
import { Button } from '../components/ui/button'
import { Card } from '../components/ui/card'
import { Input } from '../components/ui/input'
import { Select, SelectContent, SelectItem, SelectTrigger, SelectValue } from '../components/ui/select'
import { formatWhen, money } from '../lib/format'
import { useApp } from '../state/store'

type QueueFilter = 'all' | 'open' | 'resolved' | 'analyst-confirmed' | 'legitimate'

export function Alerts() {
  const { data, assignAlert, disposeAlert } = useApp()
  const [query, setQuery] = useState('')
  const [filter, setFilter] = useState<QueueFilter>('all')

  const openCount = data.alerts.filter((alert) => alert.status === 'open').length
  const visible = useMemo(() => {
    const needle = query.trim().toLowerCase()
    return data.alerts.filter((alert) => {
      if (needle && !`${alert.reference} ${alert.customer} ${alert.merchant}`.toLowerCase().includes(needle)) {
        return false
      }
      if (filter === 'open' || filter === 'resolved') return alert.status === filter
      if (filter === 'analyst-confirmed' || filter === 'legitimate') return alert.disposition === filter
      return true
    })
  }, [data.alerts, filter, query])

  return (
    <>
      <PageHeader
        eyebrow="Analyst triage"
        title="Alert queue"
        subtitle="Review suspected activity and record analyst-confirmed or legitimate outcomes."
      >
        <span className="inline-flex h-10 items-center rounded-full border border-border bg-card px-3 text-sm">
          {openCount} active
        </span>
      </PageHeader>
      <Banner>
        Suspicion is generated by heuristic rules. Only an analyst disposition marks activity confirmed or legitimate.
      </Banner>

      <Card className="p-4">
        <div className="flex flex-wrap gap-3">
          <div className="relative min-w-[240px] flex-1">
            <Icon name="search" className="pointer-events-none absolute top-1/2 left-3 -translate-y-1/2 text-muted-foreground" />
            <Input
              className="pl-10"
              value={query}
              onChange={(event) => setQuery(event.target.value)}
              placeholder="Search reference, customer, merchant"
              aria-label="Search reference, customer, merchant"
            />
          </div>
          <Select value={filter} onValueChange={(value) => setFilter(value as QueueFilter)}>
            <SelectTrigger className="w-[210px]" aria-label="Queue state">
              <SelectValue />
            </SelectTrigger>
            <SelectContent>
              <SelectItem value="all">All queue states</SelectItem>
              <SelectItem value="open">Open</SelectItem>
              <SelectItem value="resolved">Resolved</SelectItem>
              <SelectItem value="analyst-confirmed">Analyst-confirmed</SelectItem>
              <SelectItem value="legitimate">Legitimate</SelectItem>
            </SelectContent>
          </Select>
        </div>

        <div className="mt-3 divide-y divide-border">
          {visible.map((alert) => {
            const linked = data.cases.find((item) => item.internalId === alert.caseId)
            return (
              <article className="flex flex-wrap items-center gap-4 py-4" key={alert.id}>
                <div className="flex min-w-[280px] flex-1 items-start gap-3">
                  <span className={`grid size-10 place-items-center rounded-xl ${alert.status === 'open' ? 'bg-[#fff4e4] text-[#c9842a]' : 'bg-accent text-primary'}`}>
                    <Icon name="alert" />
                  </span>
                  <div>
                    <div className="flex flex-wrap items-center gap-2">
                      <Link className="font-semibold no-underline" to={`/transactions/${alert.reference}`}>{alert.merchant}</Link>
                      <Pill tone={alert.status === 'open' ? 'amber' : 'green'}>{alert.status}</Pill>
                      {alert.disposition === 'analyst-confirmed' ? <Pill tone="pink">Analyst-confirmed</Pill> : null}
                      {alert.disposition === 'legitimate' ? <Pill tone="green">Legitimate</Pill> : null}
                    </div>
                    <p className="mt-1 text-xs text-muted-foreground">
                      {alert.reference}
                      <span> · </span>
                      {alert.customer}
                      <span> · </span>
                      {formatWhen(alert.createdAt)}
                    </p>
                    {alert.caseId ? (
                      <p className="mt-1 text-sm">
                        Linked case{' '}
                        {linked ? (
                          <Link to={`/investigations?case=${linked.id}`}>{alert.caseId}</Link>
                        ) : (
                          alert.caseId
                        )}
                      </p>
                    ) : null}
                  </div>
                </div>
                <div className="flex gap-6 text-sm">
                  <p>
                    <span className="block text-xs text-muted-foreground">Amount</span>
                    <strong>{money(alert.amount)}</strong>
                  </p>
                  <p>
                    <span className="block text-xs text-muted-foreground">Heuristic</span>
                    <strong className={alert.score >= 70 ? 'text-destructive' : undefined}>
                      {alert.score} / 100
                    </strong>
                  </p>
                </div>
                <div className="ml-auto flex flex-col items-end gap-2">
                  {alert.assignee ? <span className="text-sm font-medium">{alert.assignee}</span> : null}
                  {!alert.assignee ? (
                    <Button variant="ghost" size="sm" onClick={() => assignAlert(alert.id)}>
                      <Icon name="user" /> Assign to me
                    </Button>
                  ) : null}
                  {alert.status === 'open' ? (
                    <div className="flex gap-3">
                      <Button variant="ghost" size="sm" onClick={() => disposeAlert(alert.id, 'analyst-confirmed')}>
                        Analyst-confirmed
                      </Button>
                      <Button variant="ghost" size="sm" onClick={() => disposeAlert(alert.id, 'legitimate')}>
                        Legitimate
                      </Button>
                    </div>
                  ) : null}
                </div>
              </article>
            )
          })}
          {visible.length === 0 ? <p className="py-6 text-sm text-muted-foreground">No alerts match this queue view.</p> : null}
        </div>
      </Card>
    </>
  )
}
